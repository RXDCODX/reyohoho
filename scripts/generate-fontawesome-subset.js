import { spawnSync } from 'node:child_process'
import { mkdir, readFile, readdir, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const SOURCE_ROOT = path.resolve('src')
const FONT_AWESOME_ROOT = path.resolve('node_modules/@fortawesome/fontawesome-free')
const OUTPUT_ROOT = path.resolve('src/assets/fonts')
const CSS_OUTPUT_PATH = path.resolve('src/assets/fontawesome-subset.css')
const SOURCE_EXTENSIONS = new Set(['.js', '.scss', '.vue'])
// Match only upstream icon declarations, leaving all shared behavior intact.
const ICON_MAPPING_RULE =
  /(\.fa-[a-z0-9-]+(?:\s*,\s*\.fa-[a-z0-9-]+)*)\s*\{\s*--fa\s*:\s*("(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*')\s*;?\s*\}/g
const CSS_HEADER = '/* Generated by scripts/generate-fontawesome-subset.js; do not edit. */\n'
const NON_ICON_CLASSES = new Set([
  'brands',
  'classic',
  'fw',
  'regular',
  'regular-subset',
  'solid',
  'solid-subset',
  'spin',
  'stack',
  'stack-1x',
  'stack-2x',
  'style'
])

export const collectIconNamesFromSource = (source, nonIconClasses = NON_ICON_CLASSES) => {
  const icons = new Set()
  for (const match of source.matchAll(/(?<![\w-])fa-([a-z0-9-]+)/g)) {
    if (!nonIconClasses.has(match[1])) icons.add(match[1])
  }
  return icons
}

const decodeIconCodepoint = (value) => {
  const character = value
    .slice(1, -1)
    .replace(/\\([0-9a-f]{1,6})(?:\r\n|[ \t\n\r\f])?|\\([^\n\r\f])/gi, (_, hex, literal) =>
      hex ? String.fromCodePoint(parseInt(hex, 16)) : literal
    )
  if ([...character].length !== 1) {
    throw new Error('Unsupported Font Awesome icon value: ' + value)
  }
  return character.codePointAt(0).toString(16).padStart(4, '0')
}

export const extractIconCodepoints = (css, iconNames) => {
  if (/[{;]\s*--fa\s*:/.test(css.replace(ICON_MAPPING_RULE, ''))) {
    throw new Error('Unsupported Font Awesome mapping rule; review the upstream CSS format')
  }
  const mappings = new Map()
  for (const match of css.matchAll(ICON_MAPPING_RULE)) {
    const codepoint = decodeIconCodepoint(match[2])
    for (const selector of match[1].split(',')) {
      const iconName = selector.match(/\.fa-([a-z0-9-]+)/)?.[1]
      if (iconName) mappings.set(iconName, codepoint)
    }
  }

  const missing = [...iconNames].filter((iconName) => !mappings.has(iconName))
  if (missing.length) throw new Error(`Font Awesome mappings not found: ${missing.join(', ')}`)

  return new Set([...iconNames].map((iconName) => mappings.get(iconName)))
}

export const createFontAwesomeCssSubset = (css, iconNames) => {
  // Validate every requested name before dropping anything, including old aliases.
  extractIconCodepoints(css, iconNames)
  return css.replace(ICON_MAPPING_RULE, (_, selectors, value) => {
    const usedSelectors = selectors
      .split(',')
      .map((selector) => selector.trim())
      .filter((selector) => iconNames.has(selector.slice('.fa-'.length)))
    return usedSelectors.length ? usedSelectors.join(',') + '{--fa:' + value + '}' : ''
  })
}

const listSourceFiles = async (directory) => {
  const files = []
  for (const entry of await readdir(directory)) {
    const entryPath = path.join(directory, entry)
    const entryStat = await stat(entryPath)
    if (entryStat.isDirectory()) files.push(...(await listSourceFiles(entryPath)))
    else if (SOURCE_EXTENSIONS.has(path.extname(entry))) files.push(entryPath)
  }
  return files
}

export const collectSourceIconNames = async ({ css, sourceRoot = SOURCE_ROOT }) => {
  // Derive utility names from upstream rather than maintaining another class list.
  const nonIconClasses = new Set(NON_ICON_CLASSES)
  for (const match of css.replace(ICON_MAPPING_RULE, '').matchAll(/\.fa-([a-z0-9-]+)/g)) {
    nonIconClasses.add(match[1])
  }
  const iconNames = new Set()
  for (const file of await listSourceFiles(sourceRoot)) {
    for (const iconName of collectIconNamesFromSource(
      await readFile(file, 'utf8'),
      nonIconClasses
    )) {
      iconNames.add(iconName)
    }
  }
  return iconNames
}

const subsetFont = ({ input, output, codepoints }) => {
  const command = process.platform === 'win32' ? 'pyftsubset.exe' : 'pyftsubset'
  const result = spawnSync(
    command,
    [
      input,
      `--output-file=${output}`,
      `--unicodes=${codepoints.map((codepoint) => `U+${codepoint}`).join(',')}`,
      '--flavor=woff2',
      '--layout-features=*',
      '--no-hinting'
    ],
    { stdio: 'inherit' }
  )

  if (result.error) throw result.error
  if (result.status !== 0) throw new Error(`pyftsubset failed for ${path.basename(input)}`)
}

export const generateFontAwesomeSubset = async ({ cssOnly = false } = {}) => {
  const css = await readFile(path.join(FONT_AWESOME_ROOT, 'css/fontawesome.min.css'), 'utf8')
  const iconNames = await collectSourceIconNames({ css })
  const codepoints = [...extractIconCodepoints(css, iconNames)].sort()
  const subsetCss = CSS_HEADER + createFontAwesomeCssSubset(css, iconNames)
  await writeFile(CSS_OUTPUT_PATH, subsetCss)
  const result = { icons: iconNames.size, codepoints: codepoints.length }
  if (cssOnly) return result

  await mkdir(OUTPUT_ROOT, { recursive: true })

  subsetFont({
    input: path.join(FONT_AWESOME_ROOT, 'webfonts/fa-solid-900.woff2'),
    output: path.join(OUTPUT_ROOT, 'fa-solid-subset.woff2'),
    codepoints
  })
  subsetFont({
    input: path.join(FONT_AWESOME_ROOT, 'webfonts/fa-regular-400.woff2'),
    output: path.join(OUTPUT_ROOT, 'fa-regular-subset.woff2'),
    codepoints
  })

  return result
}

const isDirectRun = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href
if (isDirectRun) {
  const result = await generateFontAwesomeSubset({ cssOnly: process.argv.includes('--css-only') })
  process.stdout.write(
    `Generated Font Awesome subsets (${result.icons} icons, ${result.codepoints} codepoints)\n`
  )
}
